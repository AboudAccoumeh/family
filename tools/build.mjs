#!/usr/bin/env node
/*
 * Validates data.json, regenerates data.js (offline fallback) and,
 * with --out <dir>, assembles the static site into that folder.
 *
 *   node tools/build.mjs              # validate + refresh data.js
 *   node tools/build.mjs --out _site  # also copy the site for deployment
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const outIdx = args.indexOf('--out');
const outDir = outIdx >= 0 ? path.resolve(args[outIdx + 1] || '_site') : null;

const errors = [], warnings = [];
let data;
const raw = fs.readFileSync(path.join(root, 'data.json'), 'utf8');
try { data = JSON.parse(raw); } catch (e) { console.error('✖ data.json is not valid JSON:\n  ' + e.message); process.exit(1); }

const people = data.people || {};
const ids = new Set(Object.keys(people));
if (!ids.size) errors.push('"people" is empty');

const year = v => { const m = v == null ? null : String(v).match(/-?\d{3,4}/); return m ? +m[0] : null; };
const STATUSES = ['married', 'divorced', 'separated', 'widowed', 'engaged', 'partner'];

for (const [id, p] of Object.entries(people)) {
  const who = `people.${id}`;
  if (!p.name) errors.push(`${who}: missing "name"`);
  if (p.gender && !['male', 'female'].includes(p.gender)) warnings.push(`${who}: gender "${p.gender}" (expected male/female)`);
  for (const k of ['father', 'mother']) {
    if (p[k] && !ids.has(p[k])) errors.push(`${who}.${k}: "${p[k]}" is not defined in people`);
    if (p[k] === id) errors.push(`${who}.${k}: a person cannot be their own parent`);
  }
  if (p.father && people[p.father] && people[p.father].gender === 'female') warnings.push(`${who}.father "${p.father}" is marked female`);
  if (p.mother && people[p.mother] && people[p.mother].gender === 'male') warnings.push(`${who}.mother "${p.mother}" is marked male`);
  const b = year(p.birth), d = year(p.death);
  if (b != null && d != null && d < b) errors.push(`${who}: death (${d}) is before birth (${b})`);
  for (const k of ['father', 'mother']) {
    const pb = people[p[k]] && year(people[p[k]].birth);
    if (b != null && pb != null && b - pb < 12) warnings.push(`${who}: born ${b}, only ${b - pb} years after ${k} "${p[k]}"`);
  }
  for (const sp of [].concat(p.spouses || [])) {
    const sid = typeof sp === 'string' ? sp : sp && sp.id;
    if (!ids.has(sid)) errors.push(`${who}.spouses: "${sid}" is not defined in people`);
  }
}

/* ancestry cycles */
const state = new Map();
const visit = id => {
  if (state.get(id) === 2) return;
  if (state.get(id) === 1) { errors.push(`cycle in parent links involving "${id}"`); return; }
  state.set(id, 1);
  for (const k of ['father', 'mother']) if (people[id][k] && ids.has(people[id][k])) visit(people[id][k]);
  state.set(id, 2);
};
ids.forEach(visit);

(data.marriages || []).forEach((m, i) => {
  const ps = m.partners || [m.a, m.b];
  const who = `marriages[${i}]`;
  if (!Array.isArray(ps) || ps.length !== 2) { errors.push(`${who}: "partners" must list exactly two ids`); return; }
  for (const pid of ps) if (!ids.has(pid)) errors.push(`${who}: "${pid}" is not defined in people`);
  if (m.status && !STATUSES.includes(String(m.status).toLowerCase())) warnings.push(`${who}: unknown status "${m.status}" (use ${STATUSES.join(', ')})`);
});

if (data.meta && data.meta.root && !ids.has(data.meta.root)) errors.push(`meta.root "${data.meta.root}" is not defined in people`);

warnings.forEach(w => console.warn('⚠ ' + w));
if (errors.length) {
  errors.forEach(e => console.error('✖ ' + e));
  console.error(`\n${errors.length} error(s) in data.json`);
  process.exit(1);
}

fs.writeFileSync(path.join(root, 'data.js'),
  '/* generated by tools/build.mjs from data.json — do not edit by hand */\nwindow.FAMILY_DATA_FALLBACK = ' + JSON.stringify(data) + ';\n');
console.log(`✔ data.json OK — ${ids.size} people, ${(data.marriages || []).length} marriages${warnings.length ? `, ${warnings.length} warning(s)` : ''}`);

if (outDir) {
  const files = ['index.html', 'styles.css', 'app.js', 'data.json', 'data.js'];
  const dirs = ['fonts', 'photos', 'images', 'assets'];
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  for (const f of files) fs.copyFileSync(path.join(root, f), path.join(outDir, f));
  for (const d of dirs) if (fs.existsSync(path.join(root, d))) fs.cpSync(path.join(root, d), path.join(outDir, d), { recursive: true });
  fs.writeFileSync(path.join(outDir, '.nojekyll'), '');
  console.log(`✔ site written to ${path.relative(root, outDir) || outDir}`);
}
